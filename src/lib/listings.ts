export function listingById(id: string) {
  return LISTINGS.find((a) => a.id === id);
}

export function listingsByDesk(desk: Desk) {
  return LISTINGS.filter((a) => a.desk === desk).sort((a, b) => {
    if (a.featured && !b.featured) return -1;
    if (!a.featured && b.featured) return 1;
    const rank = { verified: 0, new: 1, inactive: 2, unsupported: 3 };
    return rank[a.status] - rank[b.status];
  });
}
